/** Safe read-only public dashboard projection, no credentials or raw minute records. */
export function publicResearchSummary({day,review,local,evidence,budget,learning,weekly,monthly,memory}={}){
  const period=x=>x?{kind:x.kind,end:x.end,status:x.status,
   sessionsObserved:x.sessionsObserved,sessionsWithFullEvidence:x.sessionsWithFullEvidence,
   minimumFullEvidenceSessions:x.minimumFullEvidenceSessions,
   uniquePaperTrades:x.distinctPaperOutcomes?.uniqueClosed??null,
   descriptiveLearningReady:x.statisticsReadyForMonthlyLearning===true,
   proposals:(x.candidates||[]).slice(0,12).map(p=>({family:p.family,area:p.area,engines:p.engines,
    observedSessions:p.observedSessions,status:p.status,suppressed:p.suppressed,
    historicalVerdict:p.historicalVerdict,sourceKinds:p.sourceKinds,
    hypothesis:p.hypotheses?.[0]||null,eligibleForApproval:false}))}:null;
  const status=review?.status||(local?.hypotheses?.length?'LOCAL_RESEARCH_ONLY':'NO_REVIEW');
  return {day,status,mode:'PAPER_ONLY',updatedAt:review?.reviewedAt||local?.generatedAt||null,
      openaiModel:review?.model||null,summary:review?.review?.summary_ar||null,
      usage:review?.usage?{estimatedUsd:review.usage.estimatedUsd,inputTokens:review.usage.input_tokens,outputTokens:review.usage.output_tokens}:null,
      budget:budget?{calls:budget.calls||0,reservedUsd:budget.reservedUsd||0,limitUsd:3}:null,
      evidence:evidence?{status:evidence.readiness?.ok?'READY':(evidence.readiness?.reason||'INCOMPLETE'),
        aiMinutes:evidence.streams?.ai?.storedMinutes??null,scannerMinutes:evidence.streams?.scanner?.storedMinutes??null,
        missingMinutes:(evidence.streams?.ai?.missingMinutes||0)+(evidence.streams?.scanner?.missingMinutes||0)}:null,
      localHypotheses:(local?.hypotheses||[]).slice(0,5).map(x=>({id:x.id,status:x.status,observedFact:x.observedFact,
        hypothesis:x.hypothesis,experiment:x.experiment,acceptanceMetric:x.acceptanceMetric,limitation:x.limitation})),
      experiments:(review?.review?.experiments||[]).slice(0,5).map(x=>({area:x.area,hypothesis_ar:x.hypothesis_ar,
        test_ar:x.test_ar,acceptance_metric_ar:x.acceptance_metric_ar,status:x.status,confidence:x.confidence})),
      learning:learning?{status:learning.openai?.included?'OPENAI_CONNECTED_TO_STRATEGY_LEARNING':'ARCHIVE_LEARNING_ONLY',
        sourceDigest:learning.sourceDigest,recordedEvidenceComplete:learning.recordedEvidenceComplete,
        sourceTrust:learning.sourceTrust||'NOT_VERIFIED',historyReadIssues:learning.historyReadIssues?.length||0,
        learnedFrom:learning.learnedFrom,causalImprovementVerified:false,
        historicalCoverage:learning.historicalCoverage,
        scanner:{observedRows:learning.scannerMistakes?.observedRows||0,missingMinutes:learning.scannerMistakes?.missingMinutes||0,
          failedCycles:learning.scannerMistakes?.failedCycles||0,reasonKinds:Object.keys(learning.scannerMistakes?.reasons||{}).length},
        ai:{observedRows:learning.aiMistakes?.observedRows||0,missingMinutes:learning.aiMistakes?.missingMinutes||0,
          failedCycles:learning.aiMistakes?.failedCycles||0,reasonKinds:Object.keys(learning.aiMistakes?.reasons||{}).length},
        previousClosedPaper:learning.historical?.ai?.closedUnique||0,
        previousClosedScanner:learning.historical?.scanner?.closedUnique||0,
        proposalCadence:learning.proposalCadence||'DAILY_OBSERVATION_ONLY',
        memoryLoaded:learning.durableMemory?.loaded===true,
        proposals:(learning.proposals||[]).slice(0,12).map(p=>({id:p.id,family:p.family,
          priorDecision:p.priorDecision,suppressed:p.suppressedFromRecommendations===true,area:p.area,engines:p.engines,
          hypothesis_ar:p.hypothesis_ar,source:p.source,approvalStatus:p.approvalStatus,testResult:p.testResult,
          candidateKind:p.candidateStrategy?.kind,applied:false})),
        autoApply:false,manualApprovalRequired:true}:null,
      weekly:period(weekly),monthly:period(monthly),
      memory:{trackedFamilies:Object.keys(memory?.entries||{}).length,
        recordedDecisions:memory?.eventCount||0,externalProvenanceVerified:memory?.provenanceVerifiedExternally===true},
      cadence:'DAILY_OBSERVE_WEEKLY_CONSOLIDATE_MONTHLY_SAMPLE_CHECK',
      canApplyChanges:false,canTrade:false};
}
