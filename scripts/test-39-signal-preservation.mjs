import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {updateSignalHistory} from '../netlify/functions/lib/signal-history.mjs';
import {mergeDiscoveryCycleRows,mergeObservedSessionSignals,preserveSessionSignalEvidence,preserveSignalHistoryEvidence,historicalDisplayRows} from '../netlify/functions/lib/session-signal-preservation39.mjs';
let checks=0;
const eq=(actual,expected,msg)=>{assert.deepEqual(actual,expected,msg);checks++};
const day='2026-11-12';
const smart={symbol:'AAA',recommendationState:'SMART',price:12,generatedAt:'2026-11-12T14:45:00Z'};
const confirmed={symbol:'BBB',recommendationState:'CONFIRMED',price:24,target1:27,stopLoss:21,generatedAt:'2026-11-12T15:00:00Z'};
const wait={symbol:'CCC',recommendationState:'WAIT'};
const parts=[{all:[smart,wait]},{all:[confirmed]},{all:[{...wait,price:20}]}];
eq(mergeDiscoveryCycleRows(parts).map(x=>x.symbol),['AAA','CCC','BBB'],'All discovery batches preserved');
const initial={tradeDate:day,generatedAt:'2026-11-12T15:00:00Z',all:[smart,confirmed,wait]};
preserveSessionSignalEvidence(null,initial,day);
eq(initial.sessionSignalArchive.length,2,'No WAIT invented');
eq(initial.sessionSignalArchive.map(x=>x.symbol),['AAA','BBB']);
const empty={tradeDate:day,generatedAt:'2026-11-12T15:01:00Z',all:[],display8:[],top5:[]};
preserveSessionSignalEvidence(initial,empty,day);
eq(empty.sessionSignalArchive.length,2,'Empty revalidation must not erase history');
eq(historicalDisplayRows(empty).every(x=>x.tradeable===false&&x.confirmationLocked&&x.side==='WAIT'),true,'History never actionable');
const superseded={tradeDate:day,generatedAt:'2026-11-12T15:02:00Z',all:[{symbol:'AAA',recommendationState:'BAD'}]};
preserveSessionSignalEvidence(empty,superseded,day);
eq(superseded.sessionSignalArchive.find(x=>x.symbol==='AAA').supersededBy,'BAD','Terminal state recorded without fabrication');
const tomorrow={tradeDate:'2026-11-13',generatedAt:'2026-11-13T15:00:00Z',all:[]};
preserveSessionSignalEvidence(superseded,tomorrow,'2026-11-13');
eq(tomorrow.sessionSignalArchive.length,0,'No cross-session contamination');
eq(historicalDisplayRows({tradeDate:day,sessionSignalArchiveDate:'2026-11-11',sessionSignalArchive:[smart]}).length,0);
const previousWithoutArchive={tradeDate:day,generatedAt:'2026-11-12T15:03:00Z',display8:[smart],all:[]};
eq(mergeObservedSessionSignals(previousWithoutArchive,{tradeDate:day,all:[]},day).length,1,'Migrate previously saved signals');
const src=readFileSync(new URL('../public/app.js',import.meta.url),'utf8');
const match=src.match(/function dailyDisplayIdeas\(data\)\{[\s\S]*?\n\}(?=\nfunction render\(data\))/);
assert(match,'Production UI projection found');checks++;
const context=vm.createContext({});
const ideas=vm.runInContext(match[0]+'\ndailyDisplayIdeas',context);
const norm=x=>JSON.parse(JSON.stringify(x));
eq(norm(ideas({...empty,stale:true,actionable:false})).map(x=>x.symbol),['AAA','BBB'],'Closed/stale signals visible historically');
eq(norm(ideas({...empty,stale:true,actionable:false})).every(x=>x.tradeable===false&&x.confirmationLocked),true,'No stale trade activation');
eq(norm(ideas({...empty,display8:[confirmed]})).map(x=>x.symbol),['BBB','AAA'],'Live signal not duplicated by archive');
eq(norm(ideas({tradeDate:day,display8:[],all:[wait]})).length,0,'Never manufacture signals from WAIT');
const persistedHistory={dateKey:day,signals:{AAA:{lastState:'WAIT',lastPrice:12,transitions:[{state:'SMART',at:'2026-11-12T14:45:00Z'}]},BBB:{lastState:'CONFIRMED',confirmedSignals:[{signalId:'id1',confirmedAt:'2026-11-12T15:00:00Z',entry:24,entryLow:23,entryHigh:25,t1:27,sl:21}]},CCC:{lastState:'WAIT',transitions:[{state:'WAIT'}]}}};
const historyBased={tradeDate:day,generatedAt:'2026-11-12T15:15:00Z',all:[]};
preserveSignalHistoryEvidence(persistedHistory,historyBased,day);
eq(historyBased.sessionSignalArchive.map(x=>x.symbol),['AAA','BBB'],'Existing history reused without new store reads');
eq(historyBased.sessionSignalArchive[0].supersededBy,'WAIT','Old SMART marked superseded');
eq(historyBased.sessionSignalArchive[1].signalId,'id1','Original confirmed ID retained');
eq(historicalDisplayRows(historyBased).every(x=>!x.tradeable),true,'Never makes history tradable');
const noHistory={tradeDate:day,all:[]};preserveSignalHistoryEvidence(null,noHistory,day);
eq(noHistory.sessionSignalArchive.length,0,'No invented signals when history missing');

// The history writer returns the snapshot it has already retrieved and persisted.
// No extra Blob read or new scheduled invocation is needed to preserve visible signals.
const mem=new Map();let gets=0,puts=0;
const store={async get(k){gets++;return mem.get(k)??null},async setJSON(k,v){puts++;mem.set(k,structuredClone(v))}};
const recent={generatedAt:'2026-11-12T15:45:00Z',all:[smart],display8:[smart],top5:[]};
const writerResult=await updateSignalHistory(store,recent,day);
eq(writerResult.dateKey,day,'Signal writer returns actual persisted evidence');
eq(writerResult.signals.AAA.lastState,'SMART','SMART stored in history');
eq(gets,2,'No additional Blob reads beyond history and index');
eq(puts,3,'No additional writes beyond history, latest index, session index');
const nextHistory=await updateSignalHistory(store,{generatedAt:'2026-11-12T15:46:00Z',all:[],display8:[],top5:[]},day);
const afterMissing={tradeDate:day,generatedAt:'2026-11-12T15:46:00Z',all:[]};
preserveSignalHistoryEvidence(nextHistory,afterMissing,day);
eq(afterMissing.sessionSignalArchive.map(x=>x.symbol),['AAA'],'Persistent SMART not lost by empty minute');
const badStorage={async get(){throw new Error('BLOBS_OFFLINE')},async setJSON(){throw new Error('BLOBS_OFFLINE')}};
await assert.rejects(()=>updateSignalHistory(badStorage,recent,day),/BLOBS_OFFLINE/);checks++;

// Revalidation still runs at 09:46, 10:01 etc (non-discovery slots) via normal path.
const noteMatch=src.match(/function scannerVisibilityExplanation\(data\)\{[\s\S]*?\n\}(?=\nfunction render\(data\))/);
assert(noteMatch);checks++;
const note=vm.runInContext(noteMatch[0]+'\nscannerVisibilityExplanation',context);
assert.match(note({stale:true}),/لا تصلح للدخول/);checks++;
assert.match(note({scanHealth:{attemptedCount:4},display8:[]}),/لم تتأهل/);checks++;
assert.match(note({errors:['timeout'],display8:[]}),/بيانات ناقصة/);checks++;
assert(src.includes('showLevels=st==="CONFIRMED"&&!r.historicalOnly'));checks++;
const scheduled=readFileSync(new URL('../netlify/functions/daily-recommendation.mjs',import.meta.url),'utf8');
assert(scheduled.includes('const universe=focusSelection.focus.map(x=>x.symbol)'));
assert(scheduled.includes('isDiscoverySlot38(clock.minuteOfDay)'));
assert(scheduled.includes('preserveSignalHistoryEvidence(history,data,clock.dateKey)'));
checks+=3;
console.log(`DT39_SIGNAL_PRESERVATION_PASS ${checks}/${checks} (logic + UI projections; live Netlify NOT VERIFIED)`);
