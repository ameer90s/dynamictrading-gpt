import fs from 'node:fs';
import zlib from 'node:zlib';
import assert from 'node:assert/strict';
import {evaluateLiveResearch36} from '../netlify/functions/lib/research-live36.mjs';
const {bars}=JSON.parse(zlib.gunzipSync(fs.readFileSync(new URL('../tests/fixtures/alpaca_40_sessions_research_events.json.gz',import.meta.url))));
const day='2026-09-01', ticker='NOW', t=590;
const toBars=(rows,minute=t)=>rows.filter(x=>x[0]<=minute).map(x=>({datetime:`${day} ${String(Math.floor(x[0]/60)).padStart(2,'0')}:${String(x[0]%60).padStart(2,'0')}:00`,open:x[1],high:x[2],low:x[3],close:x[4],volume:x[5]}));
const stock=toBars(bars[`${day}|${ticker}`]),spy=toBars(bars[`${day}|SPY`]);
const now=new Date('2026-09-01T13:51:04Z'); // 09:51 NY, immediately after last completed 09:50 candle
const evaluate=(stockBars=stock,spyBars=spy,quote=null,opts={})=>evaluateLiveResearch36(ticker,stockBars,spyBars,quote,{now,allowHistorical:true,shariaApproved:true,...opts});
const early=evaluate();
assert.equal(early.state,'SMART','discovered setup must become SMART before a final entry candidate');
assert.equal(early.smartStage,'EARLY_DISCOVERY');
assert.equal(early.reason,'EARLY_DISCOVERY_WAIT_CONFIRMATION');
assert.equal(early.pendingCandidate,null);
assert.equal(early.canConfirmNow,false);
assert.equal(early.risk,null);
assert.equal(early.tradeable,undefined);
assert.ok(early.earlySmartEvidence?.minute<=t);
assert.equal(evaluate(stock,spy,null,{shariaApproved:false}).state,'WAIT','unapproved symbols must never be SMART');
const fakeQuote={bid:100,ask:100.03,bidSize:200,askSize:200,source:'Alpaca IEX latest quote',timestamp:'2026-09-01T13:51:02Z'};
const withQuote=evaluate(stock,spy,fakeQuote);
assert.equal(withQuote.state,'SMART','no entry candidate means no CONFIRMED even with fresh quote');
assert.equal(withQuote.risk,null);
const future={datetime:`${day} 10:02:00`,open:100,high:500,low:90,close:200,volume:99999999};
assert.equal(evaluate([...stock,future]).state,early.state,'future candle must not alter earlier SMART signal');
assert.equal(evaluate([...stock,future]).earlySmartEvidence?.eventKey,early.earlySmartEvidence?.eventKey);
const noDiscovery=evaluate(toBars(bars[`${day}|${ticker}`],584),toBars(bars[`${day}|SPY`],584));
assert.notEqual(noDiscovery.smartStage,'EARLY_DISCOVERY','opening only must not invent early SMART');
console.log('SMART_EARLY_38_PASS: discovery -> SMART, no entry/confirmation, sharia denial, quote denial, future-bar protection, opening only');
